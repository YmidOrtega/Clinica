CREATE TABLE rips_reference_codes (
    reference_table        VARCHAR(20)  NOT NULL,
    code                   VARCHAR(10)  NOT NULL,
    name                   VARCHAR(200) NOT NULL,
    service_group          VARCHAR(2)   NULL,
    for_consultations      BOOLEAN      NOT NULL,
    for_procedures         BOOLEAN      NOT NULL,
    for_emergencies        BOOLEAN      NOT NULL,
    for_hospitalization    BOOLEAN      NOT NULL,

    CONSTRAINT pk_rips_reference_codes PRIMARY KEY (reference_table, code),
    CONSTRAINT chk_rips_reference_codes_table
        CHECK (reference_table IN ('PURPOSE', 'CAUSE', 'MODALITY', 'SERVICE_GROUP', 'SERVICE')),
    CONSTRAINT chk_rips_reference_codes_group CHECK ((reference_table = 'SERVICE') = (service_group IS NOT NULL))
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci;

