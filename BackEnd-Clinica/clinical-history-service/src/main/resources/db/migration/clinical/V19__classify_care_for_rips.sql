    ADD COLUMN modality      VARCHAR(2)  NULL AFTER service_code,
    ADD COLUMN service_group VARCHAR(2)  NULL AFTER modality,
    ADD CONSTRAINT chk_encounters_care_setting
        CHECK ((service_code IS NULL AND modality IS NULL AND service_group IS NULL)
            OR (service_code IS NOT NULL AND modality IS NOT NULL AND service_group IS NOT NULL));
