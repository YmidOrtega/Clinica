CREATE TABLE admissions.service_types (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    uuid              UUID         NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0,
    name              VARCHAR(120) NOT NULL,
    kind              VARCHAR(20)  NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    status_reason     VARCHAR(500),
    status_changed_at TIMESTAMP(6),
    created_at        TIMESTAMP(6) NOT NULL,
    created_by        VARCHAR(36),
    updated_at        TIMESTAMP(6) NOT NULL,
    updated_by        VARCHAR(36),

    CONSTRAINT pk_service_types PRIMARY KEY (id),
    CONSTRAINT uq_service_types_uuid UNIQUE (uuid),
    CONSTRAINT uq_service_types_name UNIQUE (name),
    CONSTRAINT chk_service_types_kind CHECK (kind IN ('EMERGENCY', 'INPATIENT', 'OUTPATIENT')),
    CONSTRAINT chk_service_types_status CHECK (status IN ('ACTIVE', 'RETIRED')),
    CONSTRAINT chk_service_types_retirement
        CHECK ((status = 'RETIRED' AND status_reason IS NOT NULL AND status_changed_at IS NOT NULL)
            OR (status = 'ACTIVE' AND status_reason IS NULL AND status_changed_at IS NULL))
);

